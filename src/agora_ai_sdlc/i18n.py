def normalize_language(value: str | None) -> str:
    if not value:
        return "en"
    candidate = value.strip().replace("-", "_").split(".", 1)[0].split("_", 1)[0].casefold()
    return candidate if candidate in SUPPORTED_LANGUAGES else "en"


def resolve_language(explicit: str | None = None) -> str:
    if explicit:
        return normalize_language(explicit)
    for variable in ("LC_ALL", "LC_MESSAGES", "LANG"):
        value = os.environ.get(variable)
        if value:
            return normalize_language(value)
    return "en"


def t(key: str, *, lang: str = "en", **values: object) -> str:
    language = normalize_language(lang)
    template = _MESSAGES.get(language, {}).get(key) or _MESSAGES["en"].get(key)
    if template is None:
        return key
    return template.format(**values)
